import 'dart:io';

import 'os_macos.dart';
import 'os_windows.dart';

/// Граница операционной системы.
///
/// Всё, что в Dart делается по-разному на разных системах — где лежат
/// файлы, как найти чужой процесс, чем переложить звук в WAV, как показать
/// файл в проводнике, — объявлено здесь и реализовано в `os_<система>.dart`.
/// Остальной Dart пользуется только этим договором и про систему не знает
/// ничего.
///
/// Отдельно от `bridge.dart`: там разговор с родным кодом приложения
/// (перехват клавиш, микрофон, окна), и он на всех системах устроен
/// одинаково — один канал, разные реализации на той стороне. Здесь же
/// разница живёт в самом Dart.
///
/// Порт на Windows — это один новый файл `os_windows.dart` и одна строка
/// в [_forCurrentPlatform]. Ничего другого трогать не придётся:
/// `pgrep` там станет `tasklist`, `afconvert` — `ffmpeg`, `open -R` —
/// `explorer /select,`.

const appName = 'tsukiko';

/// Версия приложения. Держится рядом с именем, а не читается из pubspec:
/// прочитать его в готовой программе можно только чужой зависимостью,
/// а нужна эта строка в одном месте — при проверке обновлений.
///
/// Меняется вместе с `version:` в pubspec.yaml и с меткой выпуска.
const appVersion = '1.3.3';

/// Обратный домен приложения: им называется и папка настроек, и запись
/// в автозапуске, и bundle id на macOS.
const bundleId = 'app.yuko.tsukiko';

/// Снимок процесса: столько-то памяти и столько-то потраченного
/// процессорного времени. Само по себе бесполезно — смысл появляется
/// в разнице между двумя снимками.

/// Процесс со своей командной строкой. По ней узнаётся, чей он: имя
/// процесса у двух копий одной программы одинаковое, аргументы — нет.
typedef ProcListing = ({int pid, int rssKb, String args});

abstract class Os {
  /// Какая это система: 'macos' или 'windows'.
  ///
  /// Нужен не самой границе, а подписям (`core/labels.dart`): часть из них
  /// у систем разная — «Dock» против «панели задач». Держать их здесь
  /// нельзя: подписи переведены, переводы приходят из Flutter, а этот файл
  /// обязан собираться и без него — из него растёт отдельная программа
  /// расшифровки без единого пикселя интерфейса.
  String get platformId;

  // ── где что лежит ─────────────────────────────────────────────────────────

  /// Домашняя папка пользователя.
  String get home;

  /// Данные приложения: настройки, скачанные модели, pid сервера.
  String get supportDir;

  /// Куда по умолчанию складывать расшифровки. Обычная папка на виду,
  /// а не спрятанная в данных приложения.
  String get defaultLibraryPath;

  /// Папка документов — начальная точка для диалога выбора папки.
  String get documentsDir;

  /// Общие для системы папки, где могут лежать модели whisper, положенные
  /// не нами. Своя папка моделей сюда не входит: её знает [modelsDir].
  List<String> get sharedModelDirs;

  /// Наша папка моделей — та, куда качает загрузчик.
  String get modelsDir => join(supportDir, 'models');

  /// Собрать путь из частей. Разделитель у каждой системы свой, и
  /// склеивать строки через «/» руками — прямой путь к неработающему
  /// Windows.
  String join(String a, [String? b, String? c]) =>
      [a, ?b, ?c].join(Platform.pathSeparator);

  /// Имя файла из полного пути.
  String basename(String path) {
    final at = path.lastIndexOf(Platform.pathSeparator);
    return at < 0 ? path : path.substring(at + 1);
  }

  /// Папка, в которой лежит файл.
  String dirname(String path) {
    final at = path.lastIndexOf(Platform.pathSeparator);
    return at <= 0 ? path : path.substring(0, at);
  }

  // ── чем считать ───────────────────────────────────────────────────────────

  /// Найти программу: сначала в PATH, потом в местах, куда её кладут
  /// пакетные менеджеры этой системы. Возвращает путь или null.
  String? findExecutable(String name);

  /// Путь в том виде, в каком его можно отдать чужой программе доводом
  /// командной строки.
  ///
  /// На macOS — как есть: `execve` берёт байты не глядя, и UTF-8 доезжает
  /// целым. На Windows же довод по дороге теряет буквы, и вот почему.
  /// Dart зовёт `CreateProcessW` с широкой строкой, а `whisper-cli` и
  /// `ffmpeg` — обычные программы на C: их рантайм переводит `argv`
  /// в однобайтовую кодировку системы, и всё, что в неё не влезло,
  /// становится вопросительными знаками ещё до первой строчки их кода.
  ///
  /// Так у хозяина и не поднимался движок. Имя пользователя у него
  /// «Роман», модель лежала в
  /// `C:\Users\Роман\AppData\Roaming\…\ggml-large-v3-turbo.bin`,
  /// и whisper честно докладывал: «loading model from …», а следом
  /// «failed to open». Мы грешили на Vulkan — а обе сборки просто
  /// не открывали файл по испорченному пути.
  ///
  /// Лечится это короткими именами Windows (`GetShortPathNameW`):
  /// `C:\Users\ROMAN~1\…`. Они всегда из латиницы, поэтому и `fopen`
  /// срабатывает, и портиться в выводе движка нечему.
  String processPath(String path);

  /// Где внутри самого приложения лежит движок whisper.cpp.
  ///
  /// У каждой системы своё место: macOS велит класть вложенные программы
  /// в `Contents/Helpers`, Windows держит их просто рядом с .exe. Знать
  /// об этом должна только эта граница — остальному Dart всё равно,
  /// откуда взялся путь.
  String get engineDir;

  /// Сочетания клавиш по умолчанию: «держать и говорить» и «включить».
  ///
  /// У систем они разные не из вежливости. На macOS годится fn: клавиша
  /// свободна, лежит под мизинцем и своего смысла почти не имеет.
  /// На Windows её для программ **не существует вовсе** — Fn разбирает
  /// прошивка клавиатуры, и до приложения нажатие не доходит. Сочетание
  /// с ней там просто никогда не сработает, а человек будет думать, что
  /// сломана диктовка.
  ({List<String> mods, List<String> keys}) get defaultHold;
  ({List<String> mods, List<String> keys}) get defaultToggle;

  /// Имена файлов движка [base], от самого желанного к запасному.
  ///
  /// Списком, а не одним именем, потому что на Windows сборок две:
  /// с Vulkan и без. Какая из них годится этой машине — вопрос к системе,
  /// а не к общему коду: на macOS ответ всегда один, там Metal есть везде.
  List<String> engineNames(String base) => [base];

  // ── чем система рисует и что она спрашивает ───────────────────────────────

  /// Даёт ли система материал окна под слоем Flutter.
  ///
  /// На macOS его даёт `NSVisualEffectView`, и поповер с боковой колонкой
  /// намеренно оставлены прозрачными — иначе материала не будет видно.
  /// На Windows под окном нет ничего, и та же прозрачность оборачивалась
  /// чернотой: «Очередь пуста» на чёрном, панель у значка на чёрном.
  /// Значит фон там рисуем сами.
  bool get hasWindowMaterial;

  /// Рисует ли система строку меню сама.
  ///
  /// На macOS `PlatformMenuBar` и есть строка меню — она же раздаёт
  /// сочетания клавиш. На Windows она показывает только содержимое,
  /// и сочетания приходится развешивать самим.
  bool get hasSystemMenuBar;

  /// Нужно ли отдельное разрешение системы, чтобы перехватывать клавиши
  /// и вставлять текст в чужое окно.
  ///
  /// На macOS это «Универсальный доступ», и без него диктовка не работает
  /// вовсе. На Windows такого разрешения нет: `WH_KEYBOARD_LL` и
  /// `SendInput` доступны любому приложению. Раздел о нём там не просто
  /// лишний — он обещает человеку работу, которой не существует.
  bool get needsAccessibilityPermission;

  // ── как система называет свои вещи ────────────────────────────────────────

  /// Открыть ссылку в браузере, которым человек пользуется.
  Future<void> openUrl(String url);

  /// Имя проводника файлов: «Finder», «Проводник». Встречается в подписях
  /// кнопок, и на чужой системе «Показать в Finder» — прямая неправда.
  String get fileManagerName;

  /// Как эта система рисует модификатор в подписи к сочетанию клавиш.
  /// На macOS это значки (⌘, ⌥), на Windows — слова (Ctrl, Alt).
  String modifierLabel(String mod);

  /// Как система называет полосу со значками запущенных приложений:
  /// «Dock», «панель задач». Стоит в подписи галки, которая этот значок
  /// прячет, — и на чужой системе «значок в Dock» ничего не значит.
  String get appIconAreaName;

  /// Подпись сочетания, которым система открывает настройки приложения.
  /// Не собирается из [shortcutLabel]: между значком и клавишей здесь
  /// нет разделителя, а на Windows это может быть и вовсе не сочетание.
  String get settingsShortcut;

  /// Собрать подпись сочетания из модификаторов и клавиш.
  String shortcutLabel(List<String> mods, [List<String> keys = const []]);

  /// Подпись сочетания так, как её пишет в меню сама система.
  ///
  /// Не через [shortcutLabel]: тот разделяет части « + » и годится там,
  /// где сочетание назначают. В меню macOS ставит значки подряд и без
  /// разделителей (⇧⌘C), а Windows пишет слова через плюс
  /// (Ctrl+Shift+C) — и «⌘S» на Windows человеку не говорит ничего.
  ///
  /// Модификаторы называются по-макосному ('cmd', 'opt'), потому что
  /// оттуда же берутся и сами пункты меню: ⌘ на Windows — это Ctrl,
  /// ровно так же, как в `menu_shortcuts.dart`.
  String menuShortcut(List<String> mods, [String key = '']);

  // ── звук ──────────────────────────────────────────────────────────────────

  /// Переложить любой звук в 16 кГц моно WAV — ровно то, что whisper ест
  /// без пересчёта. Не осилили — возвращаем исходник как есть, пусть
  /// whisper попробует сам.
  Future<String> toWav(String src, String dst);

  // ── процессы ──────────────────────────────────────────────────────────────

  /// Жив ли процесс. Синхронно: спрашивают это и на выходе из приложения.
  bool isAlive(int pid);

  /// Попросить процесс завершиться ([force] — потребовать).
  void signal(int pid, {bool force = false});

  /// Все процессы с их командными строками.
  Future<List<ProcListing>> listProcesses();

  /// Сколько памяти процесс занимает на самом деле, в мегабайтах.
  ///
  /// Именно «на самом деле»: на macOS `rss` занижает всё, что пришло
  /// через mmap, а модель приходит именно так.
  Future<int> footprintMb(int pid);

  // ── система ───────────────────────────────────────────────────────────────

  /// Показать файл в проводнике системы (папку — открыть).
  ///
  /// Возвращает false, если показывать нечего. Ничего при этом не создаёт:
  /// раньше на исчезнувший файл здесь создавалась папка с его именем
  /// и открывалась — человеку показывали «запись», которой нет, а в
  /// библиотеке оставался мусор.
  Future<bool> reveal(String path);

  /// Позвать [onSignal], когда система просит приложение завершиться.
  ///
  /// Отдельным методом, потому что на Windows `ProcessSignal.sigterm.watch()`
  /// не поддерживается вовсе и бросает исключение — то есть портированное
  /// приложение падало бы на старте.
  void onTerminate(void Function() onSignal);
}

/// Реализация для системы, на которой мы работаем.
///
/// Не `final`: тесты подменяют её на свою, чтобы не ходить в настоящую
/// систему. Больше её менять некому.
Os os = _forCurrentPlatform();

Os _forCurrentPlatform() {
  if (Platform.isMacOS) return MacOs();
  if (Platform.isWindows) return WindowsOs();
  throw UnsupportedError(
      'tsukiko пока умеет работать только на macOS и Windows: для ${Platform.operatingSystem} '
      'нужна своя реализация Os (см. lib/platform/os.dart).');
}
